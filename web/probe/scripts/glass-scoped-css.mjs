#!/usr/bin/env node
// Compiles the scoped <style> blocks of the glass Vue components with Vue's
// own SFC style compiler into plain CSS for the React port, so selector
// rewriting (attribute scoping, :deep, v-bind CSS variables) and therefore
// specificity are exactly what the Vue build produces. Each component gets a
// stable scope attribute `data-v-<name>` that the React component sets on
// every element it renders, as Vue's compiler does.
//
//   node scripts/glass-scoped-css.mjs            # write glass-react/src/scoped/*.css + scopes.ts
//   node scripts/glass-scoped-css.mjs --check    # fail when the output is stale
import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, '..')
const require = createRequire(import.meta.url)
const { parse, compileStyle } = require('vue/compiler-sfc')

const srcDir = path.join(root, 'glass/src')
const outDir = path.join(root, 'glass-react/src/scoped')
const check = process.argv.includes('--check')

async function walk(dir) {
  const out = []
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name)
    if (e.isDirectory()) out.push(...await walk(p))
    else if (e.name.endsWith('.vue')) out.push(p)
  }
  return out
}

function scopeName(file) {
  return path.basename(file, '.vue').replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase()
}

// Vue derives v-bind() variable names from the scope id and the expression;
// replicate them with our stable id and report the mapping.
function cssVarsOf(source) {
  const vars = []
  const re = /v-bind\(\s*(?:'([^']+)'|"([^"]+)"|([^)]+?))\s*\)/g
  for (let m; (m = re.exec(source));) vars.push((m[1] ?? m[2] ?? m[3]).trim())
  return [...new Set(vars)]
}

const files = (await walk(srcDir)).filter(f => !f.includes(`${path.sep}components${path.sep}ui${path.sep}`)).sort()
const scopes = {}
const outputs = new Map()
for (const file of files) {
  const { descriptor, errors } = parse(await readFile(file, 'utf8'), { filename: file })
  if (errors.length) throw new Error(`${file}: ${errors[0]}`)
  const scoped = descriptor.styles.filter(s => s.scoped)
  if (!scoped.length) continue
  if (descriptor.styles.some(s => !s.scoped)) throw new Error(`${file}: unscoped <style> blocks are not handled`)
  const name = scopeName(file)
  const id = name // Vue prefixes data-v- itself
  let css = ''
  const vars = []
  for (const block of scoped) {
    const r = compileStyle({ source: block.content, filename: file, id: `data-v-${id}`, scoped: true, isProd: true })
    if (r.errors.length) throw new Error(`${file}: ${r.errors[0]}`)
    css += r.code.trim() + '\n'
    vars.push(...cssVarsOf(block.content))
  }
  // compileStyle rewrites v-bind(x) to var(--<hash>) with isProd; collect them in order.
  const emitted = [...css.matchAll(/var\(--([0-9a-z]+)\)/g)].map(m => m[1])
  const varNames = {}
  vars.forEach((expr, i) => { if (emitted[i]) varNames[expr] = `--${emitted[i]}` })
  scopes[name] = { attr: `data-v-${id}`, vars: varNames }
  const rel = path.relative(root, file)
  outputs.set(path.join(outDir, `${name}.css`), `/* Generated by scripts/glass-scoped-css.mjs from ${rel}; do not edit. */\n${css}`)
}

const ts = `// Generated by scripts/glass-scoped-css.mjs; do not edit.
// Scope attributes (and v-bind CSS variable names) for the compiled Vue
// scoped styles in ./*.css. Spread \`{ [scope.attr]: '' }\` on every element a
// component renders, exactly where Vue would add its data-v attribute.
export const scopes = ${JSON.stringify(scopes, null, 2)} as const
`
outputs.set(path.join(outDir, 'scopes.ts'), ts)

let stale = []
for (const [file, content] of outputs) {
  const current = await readFile(file, 'utf8').catch(() => null)
  if (current !== content) stale.push(path.relative(root, file))
}
if (check) {
  if (stale.length) { console.error(`stale scoped CSS: ${stale.join(', ')}; run node scripts/glass-scoped-css.mjs`); process.exit(1) }
  console.log('scoped CSS up to date')
} else {
  await mkdir(outDir, { recursive: true })
  for (const [file, content] of outputs) await writeFile(file, content)
  console.log(`wrote ${outputs.size} files: ${[...outputs.keys()].map(f => path.relative(root, f)).join(', ')}`)
}
